#!/usr/bin/env node
/**
 * Generates the app's list metadata from the OpenAPI document (D-2026-11-17-01): for every list
 * (`x-list`) its id, sort fields, default sort, searchable fields, capabilities and closed-value
 * filters (enum query params). ListPage reads this, so nothing about a list is retyped in an app.
 *
 *   node vendor/product-shell/scripts/list-meta.mjs openapi/v1.yaml src/generated/list-meta.ts
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { parse } from "yaml";

const [, , source = "openapi/v1.yaml", target = "src/generated/list-meta.ts"] = process.argv;
const text = readFileSync(source, "utf8");
const doc = source.endsWith(".json") ? JSON.parse(text) : parse(text);
const SKIP = new Set(["page", "pageSize", "q", "sort", "format", "all"]);

const lists = {};
const details = [];
for (const [path, item] of Object.entries(doc.paths ?? {})) {
  const op = item.get;
  if (!op) continue;
  if (op["x-detail"]) details.push(path);
  const meta = op["x-list"];
  if (!meta) continue;
  const filters = (op.parameters ?? [])
    .filter((p) => p.in === "query" && !SKIP.has(p.name))
    .map((p) => {
      const schema = p.schema?.$ref ? doc.components?.schemas?.[p.schema.$ref.split("/").pop()] : p.schema;
      const values = schema?.enum ?? schema?.items?.enum ?? (schema?.type === "boolean" ? ["true", "false"] : null);
      return values ? { param: p.name, values: values.map(String) } : null;
    })
    .filter(Boolean);
  lists[path] = { ...meta, filters };
}

const body = `// Generated by product-shell/scripts/list-meta.mjs from ${source}. Do not edit.
import type { ListMetaMap } from "@maqsid/product-shell";

export const LIST_META: ListMetaMap = ${JSON.stringify(lists, null, 2)};

export const DETAIL_PATHS: readonly string[] = ${JSON.stringify(details.sort(), null, 2)};
`;
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, body);
console.log(`list-meta: ${Object.keys(lists).length} lists, ${details.length} detail routes → ${target}`);
